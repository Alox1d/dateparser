#!/usr/bin/env python3
"""Generate common Kotlin rules from the attributed canonical CSV sources."""
from pathlib import Path
import csv, io, json, sys
root = Path(__file__).resolve().parents[1]
lines = ["// Generated by scripts/generate_rules.py. Do not edit.", "package io.github.alox1d.dateparser.internal", "", "internal object BundledRules {"]
for name in ("en", "ru", "regexs", "separators"):
    text = (root / "dateparser/rules" / (name + ".csv")).read_text(encoding="utf-8-sig")
    lines.append("    val " + name + " = listOf(")
    for row in list(csv.reader(io.StringIO(text), delimiter=";"))[4:]:
        if not row or not any(row): continue
        if len(row) != 6: raise ValueError(f"{name}: invalid rule {row!r}")
        word, char, errors, value, maximum, regex = row
        quote = lambda s: json.dumps(s, ensure_ascii=False).replace("$", "\\$")
        lines.append(f"        Expression({quote(word)}, {quote(char)}, {float(errors)}, {float(value)}, {float(maximum)}, {float(regex) > 0!r}".replace("True", "true").replace("False", "false") + "),")
    lines.append("    )")
lines.append("}")
output = "\n".join(lines) + "\n"
target = root / "dateparser/src/commonMain/kotlin/io/github/alox1d/dateparser/internal/BundledRules.kt"
if "--check" in sys.argv:
    if not target.exists() or target.read_text() != output: raise SystemExit("BundledRules.kt is stale; run scripts/generate_rules.py")
else:
    target.parent.mkdir(parents=True, exist_ok=True)
    target.write_text(output)
